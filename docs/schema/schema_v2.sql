-- Vues calculees ------------------------------------------------------------------------------

CREATE VIEW v_authorized_vessels AS
SELECT v.id AS vessel_id, v.name, l.number, l.expires_on
FROM vessels v JOIN licenses l ON l.vessel_id = v.id
WHERE l.status = 'active' AND l.expires_on >= CURRENT_DATE;

CREATE VIEW v_morning_board AS
SELECT w.id, w.vessel_id, v.name, w.origin, w.started_at, (CURRENT_DATE - w.started_at::date) AS age_days
FROM watch_entries w JOIN vessels v ON v.id = w.vessel_id
WHERE w.status = 'open';

CREATE VIEW v_expiring_licenses AS
SELECT l.id, l.vessel_id, l.expires_on, (l.expires_on - CURRENT_DATE) AS days_left
FROM licenses l
WHERE l.status = 'active' AND l.expires_on <= CURRENT_DATE + 90;

CREATE VIEW v_vessel_timeline AS
SELECT e.vessel_id, e.occurred_at, m.code AS module, e.type, e.summary
FROM vessel_events e JOIN module_registry m ON m.id = e.module_id;

CREATE VIEW v_repeat_offenses AS
SELECT d.vessel_id, d.captain_id, d.shipowner_id, COUNT(*) AS cases_count
FROM infraction_cases d
GROUP BY d.vessel_id, d.captain_id, d.shipowner_id;

CREATE VIEW v_seen_never_inspected AS
SELECT u.vessel_id,
       SUM(CASE WHEN u.level IN ('sighted', 'approached') THEN 1 ELSE 0 END) AS sighted_count,
       SUM(CASE WHEN u.level = 'inspected' THEN 1 ELSE 0 END) AS inspected_count
FROM observed_units u
WHERE u.vessel_id IS NOT NULL
GROUP BY u.vessel_id
HAVING SUM(CASE WHEN u.level = 'inspected' THEN 1 ELSE 0 END) = 0
   AND SUM(CASE WHEN u.level IN ('sighted', 'approached') THEN 1 ELSE 0 END) > 0;

-- Journal d'audit non modifiable (meme pour l'Admin) et main courante verrouillee ---------------

CREATE FUNCTION forbid_audit_log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$;

CREATE TRIGGER audit_log_no_update_delete BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION forbid_audit_log_change();
CREATE TRIGGER audit_log_no_truncate BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION forbid_audit_log_change();

CREATE FUNCTION forbid_locked_logbook_entry_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT status FROM logbook_days WHERE id = OLD.logbook_day_id) = 'locked' THEN
        RAISE EXCEPTION 'logbook day is locked: use a corrective entry';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER logbook_entries_locked BEFORE UPDATE ON logbook_entries
    FOR EACH ROW EXECUTE FUNCTION forbid_locked_logbook_entry_change();
