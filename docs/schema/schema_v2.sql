CREATE TABLE vessels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(190) NOT NULL,
    record_status varchar(40) NOT NULL DEFAULT 'draft' CHECK (record_status IN ('draft', 'to_match', 'validated')),
    creation_origin varchar(40) NOT NULL CHECK (creation_origin IN ('manual_entry', 'themis', 'neno', 'e_inspection', 'dpep', 'mrep')),
    category varchar(40) CHECK (category IN ('patrol_vessel', 'industrial', 'semi_industrial', 'artisanal', 'authorized_foreign', 'known_unauthorized')),
