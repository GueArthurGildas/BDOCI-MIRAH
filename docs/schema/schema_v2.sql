--
-- Traduction du schema v1 (database/docs/BOID_MIRAH_schema.sql, MySQL 8, noms francais).
-- Les noms francais d'origine sont conserves dans les commentaires de tables et de colonnes
-- (COMMENT ON ...), dans docs/GLOSSAIRE.md et docs/schema/GLOSSAIRE_COLONNES.md. Conventions : docs/schema/CONVENTIONS.md.
--
-- Ce fichier est une reference de validation : les migrations Laravel sont ecrites phase par
-- phase a partir de lui. Il s'execute tel quel sur une base PostGIS vide.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE module_registry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    label varchar(120) NOT NULL,
